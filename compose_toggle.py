"""compose_toggle — R3-вердикт РАЗВЁРТКОЙ: ролевое выравнивание на тумблерах.

Методологическая правка после замечания Кирилла: точка с прогнозом
подгоняется (не собралось при 5/25 — эксперимент сменил мир на 8/16, это
подгонка входных данных под тест). Развёртка не подгоняется: фиксированная
сетка асимметрий, ВСЕ точки в отчёте, включая «ось не завелась». Сумма
скоростей констант (24%) — темп (λ₂=0.76) одинаков у всех точек, гоняем
ЧИСТУЮ асимметрию ролей. Миры генерятся одним шаблоном, руками не правятся,
бюджет донора один для всех (2000).

Ставка (прописана ДО прогона, три способа проиграть):
  role_gap донора обязан ПРЕДСКАЗЫВАТЬ стабильность выравнивания.
  1. Флип при большом gap        → ролевое выравнивание МЕРТВО.
  2. Стабильные сдачи при gap≈0  → история про вырождение ролей НЕВЕРНА.
  3. Ось не заводится нигде, кроме симметрии → тумблеры вне области
     применимости compose; заявка сужается до каскадов.
Подтверждение ставки: монотонное соответствие gap → стабильность
(флип у симметрии, стабильность у асимметрии, где донор собрался).

Схема точки: донор (полный, медленная дорога) → цель живёт ТОЛЬКО зондом
(быстрая дорога, k донора навязан) → ввоз карты использования по роли →
экзамен на полном мире цели.

Находка первого прогона: приёмка оси судьёй НЕМОНОТОННА по бюджету
(12/12: при 1500 ось есть, при 2000 — нет). Поэтому бюджет донора — не
одна точка, а фиксированная сетка; правило (объявлено до прогона, одно
для всех): берём ПЕРВЫЙ бюджет, где ось завелась; печатаем всю картину
приёмки (+/-) — немонотонность сама по себе результат про судью.
"""

import runworld
import koopman
from compose import import_usemap, axis_with, role_gap
from fastpath import recognize_and_fit
from organism2 import Organism
from worldkit import Spec, make_glue, parse_text

runworld.Organism = Organism

PROBE, ASK = "тест", "дёрг"
DONOR_BUDGETS = (1000, 1500, 2000, 3000)   # правило: первый, где ось есть
TARGET_BUDGETS = (300, 600, 900, 1200)
# сетка: сумма скоростей 24% у всех точек (одинаковый темп λ₂),
# от симметрии (roles неразличимы) к перегибу (меньшинство голодает)
GRID = [(12, 12), (11, 13), (10, 14), (8, 16), (6, 18), (4, 20)]


def toggle_world(name, obj, vis, vv, hid, s0, s1, iv, a, b, probe_only=False):
    use = "" if probe_only else f"""
  {ASK}:
    - если {hid}={s1} то клин
    - иначе ход
"""
    return f"""мир: {name}
объекты:
  зовутся: {obj}
  видимое:
    {vis}: [{vv[0]}, {vv[1]}]
  скрытое:
    {hid}: [{s0}, {s1}]
  ловушки:
    - если {hid}={s0} то {vis}={vv[0]} (80%)
  гарантии:
    - минимум 4 объектов с {hid}={s0}
    - минимум 3 объектов с {hid}={s1}
действия:
  {PROBE}:
    - если {hid}={s0} то горит
    - иначе темно
{use}
динамика:
  каждый_шаг:
    - если {hid}={s0} то шанс_стать {s1} ({a}%)
    - если {hid}={s1} то шанс_стать {s0} ({b}%)
вмешательство:
  {iv}:
    фиксировано: {hid}={s0}
объектов: 8
"""


def glue_of(text):
    return make_glue(Spec(parse_text(text)))


def point(a, b):
    """Одна точка сетки. Возвращает (приёмка-строкой, gap, [очки])."""
    donor_txt = toggle_world(f"реле{a}_{b}", "реле", "корпус",
                             ("тёпл", "холод"), "питание", "вкл", "выкл",
                             "щёлкнуть", a, b)
    probe_txt = toggle_world(f"клапан{a}_{b}п", "клапан", "ручка",
                             ("вверх", "вниз"), "заслон", "открыт", "закрыт",
                             "переставить", a, b, probe_only=True)
    exam_txt = toggle_world(f"клапан{a}_{b}", "клапан", "ручка",
                            ("вверх", "вниз"), "заслон", "открыт", "закрыт",
                            "переставить", a, b)
    donor_org, dax, tried = None, None, []
    for db in DONOR_BUDGETS:                 # первый бюджет с осью — стоп
        org = runworld.live(glue_of(donor_txt), False, db)
        _, ax = axis_with(org, ASK)
        tried.append(f"{db}{'+' if ax is not None else '-'}")
        if ax is not None:
            donor_org, dax = org, ax
            break
    accept = " ".join(tried)
    if dax is None:
        return accept, None, []
    form = {"org": donor_org, "ax": dax, "sig": koopman.signature(dax),
            "k": dax.k}
    glue_probe, glue_exam = glue_of(probe_txt), glue_of(exam_txt)
    scores = []
    for tb in TARGET_BUDGETS:
        org, f, _, _ = recognize_and_fit(glue_probe, tb, [form])
        org.mem = import_usemap(org, f["org"], ASK, True)[0]
        s = runworld.exam(org, glue_exam, PROBE, ASK)
        scores.append(s[0] / s[1] if s[1] else 0.0)
    return accept, role_gap(dax), scores


if __name__ == "__main__":
    print(f"развёртка асимметрии тумблера (сумма скоростей 24%, "
          f"бюджеты донора {DONOR_BUDGETS}, бюджеты цели {TARGET_BUDGETS})")
    print(f"{'a/b':>7} | {'π_теор':>10} | {'приёмка донора':>20} | {'gap':>5}"
          f" | {'выравн. по бюджетам':>22} | {'мин':>4}")
    rows = []
    for a, b in GRID:
        pi1 = a / (a + b)
        accept, gap, scores = point(a, b)
        if gap is None:
            print(f"{a:>3}/{b:<3} | {1-pi1:.2f}/{pi1:.2f}  | {accept:>20} | "
                  f"{'—':>5} | {'ось не завелась':>22} |")
            rows.append((abs(b - a) / (a + b), None))
            continue
        ss = " ".join(f"{s:.2f}" for s in scores)
        stab = min(scores)
        print(f"{a:>3}/{b:<3} | {1-pi1:.2f}/{pi1:.2f}  | {accept:>20} | "
              f"{gap:>5.2f} | {ss:>22} | {stab:.2f}")
        rows.append((gap, stab))

    lived = [(g, s) for g, s in rows if s is not None]
    big = [s for g, s in lived if g >= 0.2]      # роли различимы (выучено!)
    small = [s for g, s in lived if g < 0.1]     # роли вырождены
    dead = [f"{g:.2f}" for g, s in rows if s is None]
    print("\n=== сверка со ставкой ===")
    if not lived:
        print("исход 3: ось не завелась НИГДЕ — тумблеры вне области "
              "применимости compose, заявка сужается до каскадов.")
    elif not big:
        # «устояла» без единой точки с различимыми ролями — вакуум, не
        # подтверждение: сравнивать нечего. Это сильная форма исхода 3.
        if dead:
            print("исход 3 (сильная форма): ОКНО ПУСТО. Где судья заводит "
                  "ось (около симметрии) — выученный gap≈0, выравнивание = "
                  f"монета; где роли были бы различимы — ось не заводится "
                  f"(gap_теор {', '.join(dead)}: меньшинство голодает). "
                  "Ролевое выравнивание на тумблерах не имеет области "
                  "применимости; заявка compose сужается до каскадов.")
        else:
            print("исход 3 (новая форма после фикса судьи): доноры "
                  "заводятся ВЕЗДЕ, но выученный gap < 0.2 на всех точках — "
                  "EM не воспроизводит асимметрию стационара, ролям не из "
                  "чего собраться. Следующий орган — стационар EM, не "
                  "приёмка судьи.")
        th = [f"{abs(b-a)/(a+b):.2f}->{g:.2f}" for (a, b), (g, s)
              in zip(GRID, rows) if s is not None]
        print(f"попутно: выученный стационар не воспроизводит истинную "
              f"асимметрию (gap теор->выучен: {', '.join(th)}) — EM-вырождение.")
    else:
        if min(big) < 0.9:
            print(f"исход 1: флип при большом gap {big} — "
                  f"ролевое выравнивание МЕРТВО.")
        if small and min(small) >= 0.9:
            print(f"исход 2: стабильность при gap≈0 {small} — "
                  f"история про вырождение ролей НЕВЕРНА.")
        if min(big) >= 0.9 and (not small or min(small) < 0.9):
            print("ставка устояла: gap предсказывает стабильность "
                  "(флип у симметрии, сдача у асимметрии).")
        if dead:
            print(f"точки без донора (gap_теор {', '.join(dead)}): "
                  f"перегиб морит меньшинство данными — граница слева.")
