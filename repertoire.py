"""repertoire — многоформенный репертуар + узнавание с ПОРОГОМ НОВИЗНЫ.

Открываем несколько форм медленной дорогой (organism2), складываем их
подписи (koopman). Порог «знакомого» = радиус библиотеки (recognize.py):
максимум по членам от расстояния до СВОЕГО ближайшего — чужак дальше
радиуса = форма, которой организм ещё не жил. Никаких магических констант.

Falsifiable: у каждого запроса зарегистрирован ожидаемый вердикт (семья
или «новая»), сверяем.

Миры генерируются программно (один шаблон, разные слова/скорости), чтобы
проверять именно ФОРМУ, а не файлы. У каждого — ловушка, иначе судья
медленной дороги справедливо не заводит скрытую ось (конфаунд = содержание).
"""

import koopman
import runworld
from fastpath import quick_signature
from organism2 import Organism
from worldkit import Spec, make_glue, parse_text

runworld.Organism = Organism


# ------------------------------------------------------ генераторы миров

def _rungs(hid, s, toks):
    return ("\n".join(f"    - если {hid}={s[i]} то {toks[i]}"
                      for i in range(len(s) - 1))
            + f"\n    - иначе {toks[-1]}")


def ladder(name, hid, states, probe, outs, vis, vv, iv, haz=5,
           use="жать", uouts=None):
    """3+-ступенчатая лестница вниз. Два поступенчатых читателя (зонд +
    использование), как у донора — иначе судье не хватает остатка на k>=3."""
    s, o = states, outs
    uouts = uouts or [f"u{i}" for i in range(len(s))]
    dyn = "\n".join(f"    - если {hid}={s[i]} то шанс_стать {s[i+1]} ({haz}%)"
                    for i in range(len(s) - 1))
    return f"""мир: {name}
объекты:
  зовутся: {name}
  видимое:
    {vis}: [{vv[0]}, {vv[1]}]
  скрытое:
    {hid}: [{', '.join(s)}]
  ловушки:
    - если {hid}={s[0]} то {vis}={vv[0]} (80%)
  гарантии:
    - минимум 3 объектов с {hid}={s[0]}
    - минимум 2 объектов с {hid}={s[-1]}
действия:
  {probe}:
{_rungs(hid, s, o)}
  {use}:
{_rungs(hid, s, uouts)}
динамика:
  каждый_шаг:
{dyn}
вмешательство:
  {iv}:
    фиксировано: {hid}={s[0]}
объектов: 8
"""


def toggle(name, hid, states, probe, outs, vis, vv, iv, haz=12,
           use="дёрг", uouts=("ход", "клин")):
    s0, s1 = states
    o0, o1 = outs
    return f"""мир: {name}
объекты:
  зовутся: {name}
  видимое:
    {vis}: [{vv[0]}, {vv[1]}]
  скрытое:
    {hid}: [{s0}, {s1}]
  ловушки:
    - если {hid}={s0} то {vis}={vv[0]} (80%)
  гарантии:
    - минимум 4 объектов с {hid}={s0}
    - минимум 3 объектов с {hid}={s1}
действия:
  {probe}:
    - если {hid}={s0} то {o0}
    - иначе {o1}
  {use}:
    - если {hid}={s1} то {uouts[1]}
    - иначе {uouts[0]}
динамика:
  каждый_шаг:
    - если {hid}={s0} то шанс_стать {s1} ({haz}%)
    - если {hid}={s1} то шанс_стать {s0} ({haz}%)
вмешательство:
  {iv}:
    фиксировано: {hid}={s0}
объектов: 8
"""


def glue_of(text):
    return make_glue(Spec(parse_text(text)))


# ---------------------------------------------------------- репертуар

REPERTOIRE = {
    "лестница-A": ladder("лестницаA", "давление", ["полн", "полу", "пуст"],
                         "щуп", ["выс", "сред", "низ"], "цвет",
                         ["красн", "синий"], "налить", haz=5),
    "лестница-B": ladder("лестницаB", "запас", ["много", "средне", "мало"],
                         "мерка", ["три", "два", "один"], "метка",
                         ["ярк", "блёкл"], "пополнить", haz=6),
    "тумблер-A":  toggle("тумблерA", "питание", ["вкл", "выкл"],
                         "тест", ["горит", "темно"], "корпус",
                         ["тёпл", "холод"], "щёлкнуть", haz=12),
    "тумблер-B":  toggle("тумблерB", "клапан", ["открыт", "закрыт"],
                         "поток", ["есть", "нет"], "ручка",
                         ["вверх", "вниз"], "переставить", haz=10),
}

QUERIES = {
    # медленная лестница свежими словами → семья лестниц
    ("лестница-Q", "лестница"): ladder(
        "лестницаQ", "уровень", ["высокий", "средний", "нижний"],
        "зонд", ["альфа", "бета", "гамма"], "окно",
        ["зелён", "серое"], "долить", haz=5),
    # тумблер свежими словами → семья тумблеров
    ("тумблер-Q", "тумблер"): toggle(
        "тумблерQ", "реле", ["замкн", "разомкн"],
        "прозвон", ["звон", "тишина"], "диод",
        ["светит", "тускл"], "перекинуть", haz=11),
    # та же топология, но БЫСТРАЯ → новая форма (форма = топология+темп)
    ("быстрая-лестница", None): ladder(
        "быстраяЛ", "нагрев", ["горяч", "тёплый", "остыл"],
        "касание", ["жжёт", "тепло", "холод"], "искра",
        ["видна", "нет"], "поджечь", haz=30),
    # четыре ступени → новая форма (иная размерность)
    ("глубокая-лестница", None): ladder(
        "глубокаяЛ", "стадия", ["s0", "s1", "s2", "s3"],
        "замер", ["r0", "r1", "r2", "r3"], "флаг",
        ["да", "нет"], "взвести", haz=6),
}


def discover_lib(budget=1000):
    """Подписи репертуара БЫСТРОЙ дорогой с margin-отбором k (стабильно,
    без провалов приёмки судьи). Медленная дорога/organism2 нужна отдельно
    — для КАРТ (композиция), не для узнавания формы."""
    lib = {}
    print("=== репертуар: подписи форм (быстрая дорога, margin-k) ===")
    for name, text in REPERTOIRE.items():
        s, _ = quick_signature(glue_of(text), budget)
        lib[name] = s
        print(f"  {name:14s}: k={s['k']} spec={s['spec']} "
              f"sharp={s['sharp']} ncards={s['ncards']}")
    return lib


def radius(lib, w=None):
    names = list(lib)
    r = 0.0
    for a in names:
        others = [koopman.dist(lib[a], lib[b], w) for b in names if b != a]
        if others:
            r = max(r, min(others))
    return r


def judge(lib, qsigs, w, label):
    """Один прогон узнавания при данных весах метрики. Возвращает ok/total
    и печатает разрыв знакомое/новое — главный индикатор, что порог не
    держится на подобранных константах."""
    rad = radius(lib, w)
    ok, fam_d, nov_d = 0, [], []
    print(f"\n--- веса: {label} | радиус знакомого = {rad:.2f} ---")
    for (qname, expect_family), qs in qsigs.items():
        ranked = sorted((koopman.dist(qs, lib[n], w), n) for n in lib)
        d, near = ranked[0]
        novel = d > rad
        (nov_d if novel else fam_d).append(d)
        if novel:
            verdict = "НОВАЯ ФОРМА"
            hit = expect_family is None
        else:
            verdict = f"узнан как «{near}»"
            hit = expect_family is not None and expect_family in near
        ok += hit
        mark = "✓" if hit else "✗"
        print(f"  {mark} {qname:18s}: {verdict:22s} "
              f"(ближ={d:.2f} @ {near}, k={qs['k']}, spec={qs['spec']})")
    gap = (min(nov_d) / max(fam_d)) if fam_d and nov_d and max(fam_d) > 0 \
        else float("inf")
    print(f"  итог: {ok}/{len(qsigs)}, разрыв знакомое/новое = {gap:.1f}×")
    return ok


if __name__ == "__main__":
    import sys
    lib = discover_lib()
    qsigs = {key: quick_signature(glue_of(text), 1000)[0]
             for key, text in QUERIES.items()}
    cal = koopman.calibrate(lib.values())

    if "--compare" in sys.argv:
        # эксперимент R2 (одноразовый вердикт): держалось ли узнавание на
        # рукодельных весах? Три судьи над одними подписями. Итог 15.07:
        # калиброванные 4/4 разрыв 38x, хардкод 4/4 разрыв 14x, равные 3/4
        # — константы не были несущими, калибровка их превосходит.
        for label, w in [("КАЛИБРОВАННЫЕ (из данных)", cal),
                         ("РАВНЫЕ (без настройки)", None),
                         ("старый хардкод 3/2/1/0.5",
                          {"spec": 3.0, "osc": 2.0, "sharp": 1.0,
                           "ncards": 0.5})]:
            judge(lib, qsigs, w, label)
    else:
        # рабочий вид: один судья, веса из библиотеки, никаких констант
        print(f"\nвеса метрики (калиброваны из библиотеки, не руками): "
              f"{ {c: round(v, 2) for c, v in cal.items()} }")
        judge(lib, qsigs, cal, "калиброванные")
