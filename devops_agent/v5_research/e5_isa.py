"""
E5 — ДОСТАТОЧНОСТЬ ISA. Влезают ли реальные devops-задачи в 6 мета-типов?

ISA (как проецируется) выражает: Entity/Resource/Setting/Status/Intervention/Dependency,
ТОЛЬКО булевы предикаты, per-entity ресурсы/настройки, зависимость=порядок. НЕ выражает:
числа/количества, темпоральные окна, условные/контекстные правила, разделяемую ёмкость/
контеншн, счётчики/инварианты, оптимизацию. Берём реальные задачи, считаем долю влезших.
"""

import sys

# (задача, что требует, влезает_ли, причина)
TASKS = [
    ("Развернуть svc с достаточной памятью", "resource(bool ok)+intervention", True, "базовый случай"),
    ("svc стартует только после поднятия БД", "dependency(порядок)", True, "Entity DEPENDS_ON Entity"),
    ("svc unhealthy из-за неверного config", "setting(categorical)", True, "Setting + enumerate"),
    ("Поднять с валидным TLS-сертом (выбор)", "setting(categorical)", True, "Setting"),
    ("БД нужны и диск, и поднятая реплика", "resource+dependency", True, "оба булевы+порядок"),
    ("Тюнить thread-pool в окно [lo,hi]", "resource(bool ok)+bounded-стратегия", True, "ok-предикат булев; окно — рантайм-стратегия"),
    ("error-rate < 1% за 5 мин, иначе rollback", "ТЕМПОРАЛЬНОЕ окно + число + условие", False, "нет темпоральных агрегатов, чисел, условных действий"),
    ("Масштабировать под 2× нагрузки", "ЧИСЛО/количество (ёмкость vs спрос)", False, "нет чисел/количеств (#8 убрал)"),
    ("Два svc делят хост 4GB — впихнуть оба", "разделяемая ЁМКОСТЬ/контеншн", False, "нет общих ресурсов, нет суммы≤бюджет, нет mutex (E4)"),
    ("Флаг включить только в prod, не в staging", "УСЛОВНОЕ/контекстное правило", False, "нет условных/контекстных предусловий"),
    ("Rolling update: по одному, держать N-1", "СЧЁТЧИК+инвариант+темпоральный порядок", False, "нет счётчиков/инвариантов"),
    ("Рестарт если RSS растёт (утечка)", "ТЕМПОРАЛЬНЫЙ тренд", False, "нет наблюдения динамики во времени"),
]


def main() -> None:
    print("=== E5: достаточность ISA (реальные devops-задачи в 6 типов) ===\n")
    fit = 0
    for task, needs, ok, why in TASKS:
        print(f"  [{'FIT ' if ok else 'НЕТ '}] {task}")
        print(f"          нужно: {needs} | {why}")
        fit += 1 if ok else 0
    rate = fit / len(TASKS)
    missing = "числа/количества, темпоральные окна, условные правила, разделяемая ёмкость/контеншн, счётчики/инварианты, оптимизация"
    print(f"\nвлезает: {fit}/{len(TASKS)} ({rate:.0%})")
    print("=" * 62)
    if rate < 0.7:
        print(f"ВЕРДИКТ E5: ПАДЁТ ✗ — ISA достаточна лишь для УЗКОГО класса (булево обеспечение +")
        print(f"  зависимости + categorical/bounded). Не выражает: {missing}.")
        print("  6 типов — игрушечная ISA для devops; нужна ревизия (числа, темпоральность, условия, ёмкость).")
    else:
        print("ВЕРДИКТ E5: ВЫЖИЛ ✓ — большинство реальных задач влезает (неожиданно).")


if __name__ == "__main__":
    main()
