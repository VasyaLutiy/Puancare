"""
E6 — АУДИТ СЕМАНТИЧЕСКОЙ НАГРУЗКИ. Что агент ДОБЫЛ сам vs получил готовым vs дал LLM?

«Не хардкод / контент-нейтрально» — про ЛОГИКУ кода. Но семантика откуда-то берётся.
Раскладываем каждый кусок знания/смысла по источнику. Если автономно агент открывает
пренебрежимо мало, а несущая семантика — в моих руках + LLM, то «агент учится» — преувеличение.
"""

import sys

# (кусок, источник, вес-оценка)  источник: HAND | LLM | AGENT
PIECES = [
    ("6 мета-типов (ISA/грамматика)", "HAND", "несущее"),
    ("Поверхность рычагов (какие knob'ы есть)", "HAND", "несущее"),
    ("Дефолты рычагов", "HAND", "малое"),
    ("Целевой статус (что есть успех)", "HAND", "малое"),
    ("Truth среды (footprint/окно/good-config/deps)", "HAND(среда)", "несущее"),
    ("Сенсор: exit-code → строка-симптом", "HAND", "среднее"),
    ("Библиотека стратегий (doubling/enumerate/bounded)", "HAND", "несущее"),
    ("Симптом → какой рычаг", "LLM", "несущее"),
    ("Рычаг → какой kind", "LLM", "несущее"),
    ("Направленные симптомы для bounded", "LLM", "среднее"),
    ("Какие измерения РЕЛЕВАНТНЫ (через провалы)", "AGENT", "среднее"),
    ("Конкретные ЗНАЧЕНИЯ (пороги поиском)", "AGENT", "среднее"),
    ("Плохие конфиги (bad set)", "AGENT", "малое"),
    ("Сборка графа (что с чем связать)", "AGENT", "среднее"),
]


def main() -> None:
    print("=== E6: аудит семантической нагрузки (кто что добывает) ===\n")
    from collections import Counter
    c = Counter()
    for piece, src, weight in PIECES:
        tag = src.split("(")[0]
        c[tag] += 1
        print(f"  [{src:11}] {piece}  ({weight})")
    total = len(PIECES)
    agent = c["AGENT"]
    print(f"\nисточники: HAND={c['HAND']}  LLM={c['LLM']}  AGENT={agent}  (всего {total})")
    print("=" * 62)
    # несущие куски: ISA, рычаги, truth, стратегии, симптом→рычаг, рычаг→kind — почти все HAND/LLM
    print("ВЕРДИКТ E6: ЧАСТИЧНО ✗ — автономная добыча агента РЕАЛЬНА, но УЗКА:")
    print(f"  агент сам открывает {agent}/{total} кусков — и это в основном ЗНАЧЕНИЯ и РЕЛЕВАНТНОСТЬ,")
    print("  не СЕМАНТИКУ. Несущая семантика (что значит симптом, какой kind) — у LLM;")
    print("  каркас (ISA, рычаги, сенсор, стратегии, truth) — задан руками.")
    print("  'Контент-нейтрально' верно про КОД, но 'агент сам всё понимает' — преувеличение:")
    print("  агент собирает граф и ищет значения, ВЕДОМЫЙ семантикой LLM в заданном каркасе.")


if __name__ == "__main__":
    main()
