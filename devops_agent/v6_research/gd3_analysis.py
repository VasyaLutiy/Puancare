"""
GD3 — концептуальные убийцы v6 (анализ, без прогона).
  (a) KB WRITE-ONLY: граф строим, но НИКТО его не читает/не применяет → инертен.
  (b) Поверхность knob'ов ЗАДАНА руками → «открытие структуры» ограничено моим каркасом (E6).
  (c) ЦЕНА: исчерпывающее заземление = O(сущности × knob'ы × связи) docker-проб → не масштаб.
"""

import sys

KNOBS = 3                # mem/pool/config — поверхность задана нами
DEPS_AVG = 1


def _cost_per_entity():
    # baseline + по пробе на knob + по 2 пробы (up/down) на связь + подъём целей-связей
    return 1 + KNOBS + 2 * DEPS_AVG + DEPS_AVG


def main() -> None:
    print("=== GD3: концептуальные убийцы v6 (анализ) ===\n")

    print("(a) KB WRITE-ONLY:")
    print("    граф строится, но НИ ОДИН потребитель его не читает: нет запроса, нет предсказания,")
    print("    нет действия, нет переноса поведения. Распознавание лишь метит категорию — она")
    print("    никуда не идёт. База знаний, которую никто не читает, не доказуема как полезная.\n")

    print("(b) ПОВЕРХНОСТЬ ЗАДАНА РУКАМИ (E6 на уровне v6):")
    print("    заземление «открывает» структуру, пробуя ТОЛЬКО knob'ы {mem,pool,config}, что задал Я.")
    print("    Сущность с критичным рычагом ВНЕ этой поверхности → невидима. «Агент открывает")
    print("    структуру» = «агент тычет 3 мои ручки». Реальные миры — открытый набор рычагов.\n")

    cpe = _cost_per_entity()
    print("(c) ЦЕНА не масштабируется:")
    print(f"    ~{cpe} docker-проб на сущность (baseline + {KNOBS} knob'ов + связи×2 + подъём целей).")
    print(f"    O(сущности × knob'ы × связи). Для 1000 сущностей и десятков ручек — невозможно.")
    print("    (pipeline на 4 сущности уже поднимал десятки контейнеров минутами.)\n")

    print("=" * 64)
    print("ВЕРДИКТ GD3: ТРИ РЕАЛЬНЫХ ПРОБЕЛА ✗ — KB пока write-only (нет потребителя);")
    print("  открытие ограничено заданной поверхностью; цена заземления не масштабируется.")
    print("  Нужны: ПОТРЕБИТЕЛЬ KB (запрос/применение), открытый набор рычагов, дешёвое/ленивое заземление.")


if __name__ == "__main__":
    main()
