"""qa_prompt — единый формат промпта для экзамена (exam_llm) и датасета
(build_dataset). Обучение и проверка обязаны говорить одним языком:
разъедутся форматы — счёт экзамена станет мерить формат, а не знание.
"""

DONT_KNOW = "не знаю"

SYSTEM = (
    "Ты решаешь задачи качественного анализа в закрытом мире. "
    "Отвечай РОВНО одной строкой — одним вариантом из списка, без пояснений. "
    f"Если улик недостаточно, чтобы ответить наверняка, ответь ровно: {DONT_KNOW}"
)


def build_body(q, world_text=None):
    """Текст вопроса из семпла станка (stamp_qa)."""
    vis = ", ".join(f"{k}={v}" for k, v in q["видимое"].items())
    opts = "; ".join(q["варианты"] + [DONT_KNOW])
    body = ""
    if world_text:
        body += f"Описание мира:\n```\n{world_text}\n```\n\n"
    body += (f"Мир «{q['мир']}», прошло шагов: {q['момент']}. "
             f"Порция «{q['порция']}» ({vis}). "
             f"Проба «{q['зонд']}» дала «{q['отклик']}». "
             f"Что даст проба «{q['вопрос']}» на этой порции сейчас?\n"
             f"Варианты: {opts}.")
    return body
