def axis_vector(world, action):
    """Исходы действия по значениям скрытой оси (в их порядке) или None,
    если действие не читает ось (шумовое/сущностное/вмешательство)."""
    key = world["ключ"]
    if world["спец"] and action in SPECIAL.get(key, {}):
        m = SPECIAL[key][action]
        return [m[w][0] for w, _ in world["значения"]]
    if action in ACT2PROBE and ACT2PROBE[action] in world["пробы"]:
        pid = ACT2PROBE[action]
        default = PROBES[pid]["дефолт"]
        return [OUTCOME.get((g, pid), default) for _, g in world["значения"]]
    return None


def axis_actions(world):
    """Имена действий мира, читающих скрытую ось."""
    if world["спец"]:
        return list(SPECIAL.get(world["ключ"], {}))
    return [PROBES[p]["действие"] for p in world["пробы"]]


# ----------------------------------------------------------------- проверки

def _self_check():
    for w in WORLDS:
        имя, ось = w["файл"], w["ось"]
        значения = [v for v, _ in w["значения"]]

        # R2: ось — минимум 2 значения.
        assert len(значения) >= 2, f"{имя}: у оси <2 значений"
        assert len(значения) == len(set(значения)), f"{имя}: дубль значения оси"

        # R2: зонд и вопрос читают ОДНУ ось и различают её (>=2 исходов).
        зонд, вопрос = w["экзамен"]
        act = set(axis_actions(w))
        for a in (зонд, вопрос):
            assert a in act, f"{имя}: экзаменационное {a!r} не читает ось"
            vec = axis_vector(w, a)
            assert vec is not None and len(set(vec)) >= 2, \
                f"{имя}: {a!r} не различает ось (исходы {vec})"

        # (б) зонд экзамена != вопрос (иначе экзамен тавтологичен).
        assert зонд != вопрос, f"{имя}: зонд == вопрос экзамена ({зонд!r})"

        # (а) СОВМЕСТНАЯ сигнатура всех действий мира различает ВСЕ пары
        # значений оси. Ловит фантомную ось: если два значения дают
        # одинаковый исход у КАЖДОГО действия — они неразличимы (старый m12:
        # арен и алкан молчали и у P1, и у P2 — ось k=3 была фиктивной).
        vectors = [v for a in act
                   for v in [axis_vector(w, a)] if v is not None]
        for i in range(len(значения)):
            for j in range(i + 1, len(значения)):
                assert any(vec[i] != vec[j] for vec in vectors), \
                    (f"{имя}: значения оси {значения[i]!r} и {значения[j]!r} "
                     f"неразличимы совместной сигнатурой действий (фантом)")

        # R5: вмешательство есть.
        assert w["вмешательство"], f"{имя}: нет вмешательства (R5)"

        # R7: масштаб — 8 объектов, 2..6 значений на атрибут.
        assert w["объектов"] == 8, f"{имя}: объектов != 8"
        for a, vals in w["видимое"].items():
            assert 2 <= len(vals) <= 6, f"{имя}: атрибут {a} вне 2..6"
        assert 2 <= len(значения) <= 6, f"{имя}: ось вне 2..6"

        # Гарантия >=2 объекта на каждое значение оси (генерит forge, тут —
        # проверимость: 8 объектов делятся на k значений по >=2).
        assert 2 * len(значения) <= w["объектов"], \
            f"{имя}: 8 объектов не покрывают {len(значения)} значений по 2"

        # Ловушки: корреляция видимого с осью 70..90%.
        assert 1 <= len(w["ловушки"]) <= 2, f"{имя}: ловушек не 1..2"
        for (ha, hv, va, vv, p) in w["ловушки"]:
            assert ha == ось, f"{имя}: ловушка не по оси"
            assert hv in значения, f"{имя}: ловушка на чужое значение оси"
            assert va in w["видимое"] and vv in w["видимое"][va], \
                f"{имя}: ловушка на необъявленное видимое"
            assert 70 <= p <= 90, f"{имя}: ловушка {p}% вне 70..90"

    # m16 — все слова m01 покрыты словарём переименования.
    src = WORLD_BY_KEY["m01"]
    tokens = {src["файл"], "реактив", src["ось"]}
    for a, vals in src["видимое"].items():
        tokens.add(a); tokens.update(vals)
    tokens.update(v for v, _ in src["значения"])
    for p in src["пробы"]:
        tokens.add(PROBES[p]["действие"])
        default = PROBES[p]["дефолт"]
        for _, g in src["значения"]:
            tokens.add(OUTCOME.get((g, p), default))
    tokens.add(src["вмешательство"][0])
    missing = {t for t in tokens if t not in RENAME}
    assert not missing, f"m16: словарь не покрывает слова m01: {missing}"


_self_check()


