def normalize_group(name):
    """Слово группы -> канон (§6 списка): пробелы в подчёркивания, обрезка."""
    return str(name).strip().replace(" ", "_")


def outcome_of(groupkey, pid):
    """Табличный исход пробы pid для внутренней группы (или дефолт/None)."""
    if groupkey is None:
        return PROBES[pid]["дефолт"]
    return OUTCOME.get((groupkey, pid), PROBES[pid]["дефолт"])


def combine_probe(outcomes, default):
    """КОМБИНИРОВАНИЕ проб (§6): исход пробы на молекуле из нескольких групп.
    оба/все дефолтные -> дефолт; ровно один недефолтный -> он; совпали -> он;
    разные недефолтные -> «двойной_отклик» (объявленное упрощение)."""
    nd = [o for o in outcomes if o != default]
    if not nd:
        return default
    if all(o == nd[0] for o in nd):
        return nd[0]
    return "двойной_отклик"


def judge_molecule(groups):
    """Суд оракула над набором групп молекулы (§6). Возвращает (ok, причина).
    Причина — с префиксом-классом (схема:/запрет:/пустышка:) для панели."""
    gs = [normalize_group(g) for g in (groups or [])]
    if not (1 <= len(gs) <= 2):
        return False, "схема: групп не 1..2"
    for g in gs:
        if g not in MOLECULE_GROUPS:
            return False, "схема: группа вне списка 14"
    if len(set(gs)) < len(gs):
        return False, "запрет: одна группа дважды"
    if len(gs) == 2 and frozenset(gs) in FORBIDDEN_PAIRS:
        return False, "запрет: самореагирующая пара"
    if not any(g in DYNAMIC_IN_AIR for g in gs):
        return False, "пустышка: нет динамической группы"
    return True, "ок"


def _mol_self_check():
    # Динамика ∪ статика = ровно 14 групп выбора, без пересечений.
    dyn, stat = set(DYNAMIC_IN_AIR), set(STATIC_KEY)
    assert dyn | stat == set(MOLECULE_GROUPS), \
        f"§6: динамика∪статика != список 14 ({(dyn | stat) ^ set(MOLECULE_GROUPS)})"
    assert not (dyn & stat), f"§6: группа и динамична и статична: {dyn & stat}"
    # У каждой динамической группы существует полностью детерминированная
    # экзаменная пара стандартных проб (совместная сигнатура различает все
    # пары значений оси) — иначе экзамен формы невозможен.
    for g, info in DYNAMIC_IN_AIR.items():
        keys = [k for _, k in info["значения"]]
        n = len(keys)
        pids = list(PROBES)
        ok_pair = any(
            all(outcome_of(keys[i], a) != outcome_of(keys[j], a)
                or outcome_of(keys[i], b) != outcome_of(keys[j], b)
                for i in range(n) for j in range(i + 1, n))
            for a in pids for b in pids if a != b)
        assert ok_pair, f"§6: у {g} нет полностью детерминированной пары проб"
    # combine_probe — контракт §6 на парах.
    assert combine_probe(["нет", "нет"], "нет") == "нет"
    assert combine_probe(["газ", "нет"], "нет") == "газ"
    assert combine_probe(["газ", "газ"], "нет") == "газ"
    assert combine_probe(["газ", "шип"], "нет") == "двойной_отклик"


_mol_self_check()
